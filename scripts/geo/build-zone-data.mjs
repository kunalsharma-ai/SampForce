#!/usr/bin/env node
/**
 * Builds the time-zone data behind the client time and "best time to connect" card (ADR 0089).
 *
 * Sources (see scripts/geo/README.md for licences and attribution):
 *   - dr5hn/countries-states-cities-database countries.json and states.json (ODbL 1.0): ISO 3166-1 alpha-3 codes,
 *     UN subregions, each country's IANA zones, and the zone of each state or province
 *   - apps/api/assets/geo/cities.json.gz (built by build-geo-data.mjs from GeoNames): which state a city is in
 *
 * Usage: node scripts/geo/build-zone-data.mjs <countries.json> <states.json>
 * Writes packages/types/src/geo-zones.ts. Every zone written is checked against the running Node's time-zone data,
 * and a state's zone is kept only when it is one of its country's zones (the source has a few wrong ones).
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';

const [countriesFile, statesFile] = process.argv.slice(2);
if (!countriesFile || !statesFile) {
  console.error('usage: build-zone-data.mjs <countries.json> <states.json>');
  process.exit(1);
}
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', '..');
const countries = JSON.parse(fs.readFileSync(countriesFile, 'utf8'));
const states = JSON.parse(fs.readFileSync(statesFile, 'utf8'));
const cityRows = JSON.parse(zlib.gunzipSync(fs.readFileSync(path.join(root, 'apps/api/assets/geo/cities.json.gz'))).toString('utf8'));

const valid = (zone) => {
  try {
    new Intl.DateTimeFormat('en', { timeZone: zone });
    return true;
  } catch {
    return false;
  }
};

/** Where most people and businesses are, for countries that span several zones. Checked by hand. */
const MAIN_ZONE = {
  AQ: 'Antarctica/McMurdo', AR: 'America/Argentina/Buenos_Aires', AU: 'Australia/Sydney', BR: 'America/Sao_Paulo', CA: 'America/Toronto',
  CL: 'America/Santiago', CN: 'Asia/Shanghai', CY: 'Asia/Nicosia', CD: 'Africa/Kinshasa', EC: 'America/Guayaquil', PF: 'Pacific/Tahiti',
  DE: 'Europe/Berlin', GL: 'America/Nuuk', ID: 'Asia/Jakarta', KZ: 'Asia/Almaty', KI: 'Pacific/Tarawa', MY: 'Asia/Kuala_Lumpur',
  MH: 'Pacific/Majuro', MX: 'America/Mexico_City', FM: 'Pacific/Pohnpei', MN: 'Asia/Ulaanbaatar', MA: 'Africa/Casablanca',
  NZ: 'Pacific/Auckland', NO: 'Europe/Oslo', PS: 'Asia/Hebron', PG: 'Pacific/Port_Moresby', PT: 'Europe/Lisbon', RU: 'Europe/Moscow',
  ES: 'Europe/Madrid', UA: 'Europe/Kyiv', US: 'America/New_York', UM: 'Pacific/Wake', UZ: 'Asia/Tashkent',
};
/** Corrections to the source's state zones. */
const STATE_FIX = { US: { AS: 'Pacific/Pago_Pago', GU: 'Pacific/Guam', MP: 'Pacific/Saipan', PR: 'America/Puerto_Rico', VI: 'America/St_Thomas', UM: 'Pacific/Wake', IN: 'America/Indiana/Indianapolis' } };

const fold = (s) => s.normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();

const facts = {};
const stateZones = {};
const cityZones = {};
let stateCount = 0;
let cityCount = 0;
for (const c of countries) {
  const code = c.iso2;
  const zones = (c.timezones ?? []).map((t) => t.zoneName).filter(valid);
  const main = MAIN_ZONE[code] ?? zones[0];
  if (!main || !valid(main)) {
    console.warn(`no zone for ${code}`);
    continue;
  }
  facts[code] = [c.iso3, c.subregion || c.region || '', main];
  if (zones.length < 2) continue;
  const byState = {};
  const fix = STATE_FIX[code] ?? {};
  for (const s of states.filter((x) => x.country_code === code)) {
    const zone = fix[s.iso2] ?? s.timezone;
    if (!zone || !valid(zone) || !(zones.includes(zone) || fix[s.iso2])) continue;
    if (s.iso2) byState[s.iso2.toUpperCase()] = zone;
    byState[fold(s.name)] = zone;
    stateCount++;
  }
  if (!Object.keys(byState).length) continue;
  stateZones[code] = byState;
  // Cities of 100,000+ people, so "Los Angeles, USA" with no state still finds its zone. 0 stands for the country's
  // main zone (it keeps the file small). Cities in a state the source has no zone for are left out.
  const byCity = {};
  for (const [name, region, population] of cityRows[code] ?? []) {
    if (population < 100_000 || !region) continue;
    const zone = byState[region.toUpperCase()];
    const key = fold(name);
    if (!zone || key in byCity) continue;
    byCity[key] = zone === main ? 0 : zone;
    cityCount++;
  }
  if (Object.keys(byCity).length) cityZones[code] = byCity;
}

const json = (o) => JSON.stringify(o);
const out = `/* Generated by scripts/geo/build-zone-data.mjs. Do not edit by hand. */

/** ISO 3166-1 alpha-2 → [alpha-3, UN subregion, the zone most of the country's business runs on]. */
export const GEO_COUNTRY_FACTS: Readonly<Record<string, readonly [string, string, string]>> = ${json(facts)};

/** For countries with several zones: state code (upper case) or folded state name → IANA zone. */
export const GEO_STATE_ZONES: Readonly<Record<string, Readonly<Record<string, string>>>> = ${json(stateZones)};

/** For countries with several zones: folded name of a city of 100,000+ people → IANA zone (0 = the main zone). */
export const GEO_CITY_ZONES: Readonly<Record<string, Readonly<Record<string, string | 0>>>> = ${json(cityZones)};
`;
fs.writeFileSync(path.join(root, 'packages/types/src/geo-zones.ts'), out);
console.log(`countries ${Object.keys(facts).length}, state zones ${stateCount}, city zones ${cityCount}, ${(out.length / 1024).toFixed(0)} KB`);
