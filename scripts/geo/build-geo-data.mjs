#!/usr/bin/env node
/**
 * Builds SampForce's country, region and city data (company-centric CRM, location pickers).
 *
 * Sources (see scripts/geo/README.md for licences and attribution):
 *   - countries-and-timezones 3.11.0 (MIT): ISO 3166-1 countries and their IANA time zones
 *   - libphonenumber-js (MIT): international dialling codes
 *   - country-to-currency 3.0.2 (MIT): each country's currency (ISO 4217)
 *   - dr5hn/countries-states-cities-database states.json (ODbL 1.0): states, provinces and regions
 *   - all-the-cities 3.1.0 (MIT code, GeoNames data CC BY 4.0): places with 1,000+ people
 *
 * Usage: node scripts/geo/build-geo-data.mjs <dir with node_modules holding the four packages> <states.json>
 * Writes packages/types/src/geo-countries.ts and apps/api/assets/geo/{regions,cities}.json.gz.
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import zlib from 'node:zlib';

const [srcDir, statesFile] = process.argv.slice(2);
if (!srcDir || !statesFile) {
  console.error('usage: build-geo-data.mjs <node_modules parent dir> <states.json>');
  process.exit(1);
}
const req = createRequire(path.join(path.resolve(srcDir), 'index.js'));
const ct = req('countries-and-timezones');
const lp = req('libphonenumber-js');
const curMod = req('country-to-currency');
const currencyOf = curMod.default ?? curMod;
const cities = req('all-the-cities');
const states = JSON.parse(fs.readFileSync(statesFile, 'utf8'));

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', '..');
// Territories libphonenumber has no metadata for: their ITU codes.
const EXTRA_DIAL = { AQ: '672', GS: '500', HM: '672', PN: '64', TF: '262', UM: '1' };
// Uninhabited territories without an IANA zone of their own: the fixed offset they keep (UTC+5).
const EXTRA_TZ = { HM: ['Etc/GMT-5'] };

const countries = Object.values(ct.getAllCountries())
  .map((c) => ({
    code: c.id,
    dial: lp.getCountries().includes(c.id) ? lp.getCountryCallingCode(c.id) : EXTRA_DIAL[c.id],
    currency: currencyOf[c.id],
    timezones: c.timezones.length ? c.timezones : EXTRA_TZ[c.id],
    name: c.name,
  }))
  .sort((a, b) => a.code.localeCompare(b.code));
for (const c of countries) if (!c.dial || !c.currency || !c.timezones?.length) throw new Error(`incomplete ${c.code}`);

const ts = `/* Generated by scripts/geo/build-geo-data.mjs. Do not edit by hand. */

/** [ISO 3166-1 alpha-2, English name, dialling code without +, ISO 4217 currency, IANA time zones]. */
export const GEO_COUNTRY_ROWS: ReadonlyArray<readonly [string, string, string, string, readonly string[]]> = [
${countries.map((c) => `  [${JSON.stringify(c.code)}, ${JSON.stringify(c.name)}, ${JSON.stringify(c.dial)}, ${JSON.stringify(c.currency)}, ${JSON.stringify(c.timezones)}],`).join('\n')}
];
`;
fs.writeFileSync(path.join(root, 'packages/types/src/geo-countries.ts'), ts);

// Regions: { [country]: [[code, name, type]] }, level-1 subdivisions only.
const regions = {};
const byCountry = {};
for (const s of states) {
  if (s.level && String(s.level) !== '1' && s.parent_id) continue;
  (byCountry[s.country_code] ??= []).push(s);
  (regions[s.country_code] ??= []).push([s.iso2, s.name, s.type ?? '']);
}
for (const list of Object.values(regions)) list.sort((a, b) => a[1].localeCompare(b[1]));

// Cities: { [country]: [[name, regionCode or '', population]] }, largest first.
const out = {};
for (const city of cities) {
  const st = byCountry[city.country] ?? [];
  const m = st.find((x) => x.fips_code === city.adminCode) ?? st.find((x) => x.iso2 === city.adminCode);
  (out[city.country] ??= []).push([city.name, m?.iso2 ?? '', city.population]);
}
for (const list of Object.values(out)) list.sort((a, b) => b[2] - a[2] || a[0].localeCompare(b[0]));

const dataDir = path.join(root, 'apps/api/assets/geo');
fs.mkdirSync(dataDir, { recursive: true });
fs.writeFileSync(path.join(dataDir, 'regions.json.gz'), zlib.gzipSync(JSON.stringify(regions), { level: 9 }));
fs.writeFileSync(path.join(dataDir, 'cities.json.gz'), zlib.gzipSync(JSON.stringify(out), { level: 9 }));
console.log(`${countries.length} countries, ${states.length} regions, ${cities.length} cities`);
